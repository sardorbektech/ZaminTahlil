  let currentLang = localStorage.getItem("zamintahlil_lang") || "uz-latn";
  if (!DICTS[currentLang]) {
    currentLang = "uz-latn";
  }

  function getNested(obj, path) {
    const parts = path.split(".");
    let curr = obj;
    for (const part of parts) {
      if (curr === null || curr === undefined || typeof curr !== "object") {
        return undefined;
      }
      curr = curr[part];
    }
    return curr;
  }

  function t(key, vars = {}) {
    const dict = DICTS[currentLang] || DICTS["uz-latn"];
    let text = getNested(dict, key);
    if (text === undefined) {
      text = getNested(DICTS["uz-latn"], key);
    }
    if (text === undefined) {
      return key;
    }
    if (typeof text !== "string") {
      return text;
    }
    for (const [vKey, vVal] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${vKey}\\}`, "g"), vVal);
    }
    return text;
  }

  function setLanguage(lang) {
    if (!DICTS[lang]) return;
    currentLang = lang;
    localStorage.setItem("zamintahlil_lang", lang);
    document.documentElement.lang = lang.startsWith("uz") ? "uz" : lang;
    applyTranslations();
    window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
  }

  function applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      el.textContent = t(key);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      el.placeholder = t(key);
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      el.title = t(key);
    });
  }

  window.i18n = {
    t,
    setLanguage,
    getLanguage: () => currentLang,
    applyTranslations,
    getDicts: () => DICTS,
  };
